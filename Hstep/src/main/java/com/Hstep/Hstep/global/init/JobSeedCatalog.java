    private static TrackJobSeed track(
            String trackName,
            JobCategory category,
            String jobNames
    ) {
        List<JobSeed> jobs = Arrays.stream(jobNames.strip().split("\\R"))
                .map(String::trim)
                .filter(name -> !name.isBlank())
                .distinct()
                .map(name -> new JobSeed(name, category))
                .toList();

        return new TrackJobSeed(trackName, jobs);
    }

